//
// The viewer reads a committed data file rather than shelling out to git at runtime. This
// VPS cannot reliably reap child processes - the same fault that hangs `next build` and the
// pm2 daemon - so spawning git from a page request would eventually hang that request.
// Generating at development time keeps the page a plain read.
//
// Run after adding commits, before deploying:
//   npm run changelog:generate

