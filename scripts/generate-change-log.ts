function gitLog() {
  const raw = execFileSync("git", ["log", "--reverse", "--date=short", "--pretty=format:%ad\x1f%h\x1f%s"], {
    cwd: path.join(__dirname, ".."),
    encoding: "utf8",
    maxBuffer: 20 * 1024 * 1024
  });
  return raw.split("\n").filter(Boolean).map((line, index) => {
    const [date, commit, title] = line.split("\x1f");
    return { number: index + 1, date, commit, title, request: REQUESTS[commit] };
  });
}

const entries = gitLog();
const file = `// Generated by scripts/generate-change-log.ts - do not edit by hand.
// Regenerate with: npm run changelog:generate

import type { ChangeLogEntry } from "@/lib/change-log";

export const CHANGE_LOG: ChangeLogEntry[] = ${JSON.stringify(entries, null, 2)};
`;

const target = path.join(__dirname, "..", "lib", "change-log-data.ts");
writeFileSync(target, file, "utf8");
console.log(`Wrote ${entries.length} change log entries to ${target}`);
